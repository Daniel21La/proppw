export function useT() {
    return {
        t: (path) => {
            const keys = path.split('.');
            let current = translations[currentLang.value] || translations.id;
            for (const key of keys) {
                if (current && current[key] !== undefined) {
                    current = current[key];
                } else {
                    return path;
                }
            }
            return current;
        },
        currentLang,
        setLanguage,
    };
}
